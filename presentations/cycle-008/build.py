"""The Heeded Column — cycle 008 presentation (the Atelier, 2026-10-16).

Collects every number the page states into data.js, from this cycle's three sessions
(window/cycle-008-session-{1,2,3}/results.json, committed) and from four sibling files read
at pinned commits (hashes checked below; the files are not committed here):

  python3 -I build.py <field14.json> <field17c.json> <field18.json> <studio_summary.json>

field14  = field-research@665d729 artifacts/2026-10-14-the-warnings-never-needed/data/results.json
field17c = field-research@665d729 artifacts/2026-10-15-the-end-written-in-advance/correction-2026-10-16/results.json
field18  = field-research@665d729 artifacts/2026-10-16-the-clock-and-the-record/data/results.json
studio   = studio@0a27b6b works/2026-10-16-filed-under/summary.json

Nothing is recomputed from the siblings' data: their numbers are quoted as published.
"""
import hashlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
WIN = os.path.join(HERE, '..', '..', 'window')
PINS = {
    'field14': '2d5a3de4b7c5a543f270b8f88cb01d22acf9f730aa4a4adcc11f915cc3b65f22',
    'field17c': '59c8ed807eb401581f029dc740e776146590f020c40174bd4d53662b25c8965f',
    'field18': '15a28c4a7dcb76f9041eb110128b7a02a806a4541918c51799f4c07550521636',
    'studio': '409e816567b9fafb67d1377d6ddbda6089ee1df401df2ba8dd53b50f812ce834',
}


def load(path, pin=None):
    raw = open(path, 'rb').read()
    if pin and hashlib.sha256(raw).hexdigest() != pin:
        sys.exit(f'hash mismatch: {path}')
    return json.loads(raw)


def main(f14, f17, f18, st):
    s1 = load(os.path.join(WIN, 'cycle-008-session-1', 'results.json'))
    s2 = load(os.path.join(WIN, 'cycle-008-session-2', 'results.json'))
    s3 = load(os.path.join(WIN, 'cycle-008-session-3', 'results.json'))
    a = load(f14, PINS['field14']); b = load(f17, PINS['field17c'])
    c = load(f18, PINS['field18']); d = load(st, PINS['studio'])
    w20 = c['windows']['20']
    real = {
        'clock': {
            'settings': s1['settings'], 'first': s1['first_year'], 'last': s1['last_year'],
            'quiet_years': s1['quiet_years'], 'bound_pct': round(100 * s1['q95_upper_rate'], 2),
            'percent_figures': s1['percent_figures_on_page'],
        },
        'bank': {
            'fans': s2['n_reports'], 'mode_within_half': s2['h8']['mode_within_half_point'],
            'outturn_within_half': s2['h8']['outturn_within_half_point'],
            'reports': s3['reports'], 'gap_sigma': s3['gap']['mean_ratio_to_u'],
            'gap_sigma_max': s3['gap']['max_ratio_to_u'], 'within_tenth': s3['gap']['within_tenth'],
            'held_n': s3['held']['n'], 'held_closer': s3['held']['const_closer'],
            'mae_const': s3['held']['mae_const'], 'mae_market': s3['held']['mae_market'],
        },
        'tornado': {
            'warnings': a['frame']['warnings'], 'met': a['V']['all']['k'],
            'far_pct': round(100 * a['V']['all']['far'], 1),
            'far_strict_pct': round(100 * a['S']['all']['far'], 1),
            'before': w20['before']['pct'], 'after': w20['after']['pct'],
            'diff': w20['diff_after_minus_before_points'], 'ci': w20['diff_ci95'],
            'placebo': c['placebo_20']['diff_after_minus_before_points'],
        },
        'local': {
            'dealt': d['dealt'], 'withheld': d['withheld_not_dealt'],
            'heeded_backed': d['heeded_backed'], 'ignored_backed': d['ignored_backed'],
            'nn_contradicted': d['never_needed']['contradicted'],
            'nn_backed': d['never_needed']['backed'], 'nn_none': d['never_needed']['none'],
            'silent': b['P1']['silent'], 'silent_with_expiry': b['P1']['with_expiry_after_sent'],
            'median_life_h': b['P2']['median_min'] / 60,
            'cancel_before_pct': round(100 * b['P3']['share'], 1),
            'cancels': b['P3']['cancelled_with_expiry'],
        },
    }
    with open(os.path.join(HERE, 'data.js'), 'w') as fh:
        fh.write('// generated by build.py; every real number the page states\n')
        fh.write('window.REAL=' + json.dumps(real, indent=1) + ';\n')
    print(json.dumps(real, indent=1))


if __name__ == '__main__':
    main(*sys.argv[1:5])
