#!/usr/bin/env python3
"""The Hundred Occasions. Cycle 008, session 2. A keeper that writes probabilities and acts on them:
the Bank of England's CPI inflation fan charts, February 2004 to November 2013, against the outturn.

  python3 -I build.py <fanplot_3.4.2.tar.gz> <d7g7.csv>
     fanplot (CRAN, GPL-2) is used only as a reader: its data/boe.RData holds the Bank's spreadsheet
     'Parameters for MPC CPI Inflation Projections from February 2004' (Nov 2013 Report). Needs pyreadr.
     d7g7.csv: ONS series D7G7, CPI annual rate (Open Government Licence v3.0).
  writes data.js (parameters, outturns, per-report reads) and results.json. Both inputs hash-checked."""
import csv, hashlib, io, json, math, os, sys, tarfile, tempfile
here = os.path.dirname(os.path.abspath(__file__))
SRC = json.load(open(os.path.join(here, 'sources.json')))['sources']
sha = lambda f: hashlib.sha256(open(f, 'rb').read()).hexdigest()
tgz, ons = sys.argv[1], sys.argv[2]
assert sha(tgz) == SRC['fanplot']['sha256'], 'fanplot hash'; assert sha(ons) == SRC['ons']['sha256'], 'ons hash'
import pyreadr
with tempfile.TemporaryDirectory() as td:
    tarfile.open(tgz).extract('fanplot/data/boe.RData', td, filter='data')
    df = list(pyreadr.read_r(os.path.join(td, 'fanplot/data/boe.RData')).values())[0]
B = [dict(t0=float(r.time0), t=float(r.time), m=float(r.mode), u=float(r.uncertainty), g=float(r.skew)) for r in df.itertuples()]
assert len(B) == 512
CPI = {}
for r in csv.reader(open(ons)):
    if len(r) == 2 and ' Q' in r[0]:
        y, q = r[0].split(' Q'); CPI[int(y) + (int(q) - 1) / 4] = float(r[1])
assert CPI[2004.0] == 1.3 and CPI[2008.5] == 4.8
Phi = lambda z: 0.5 * (1 + math.erf(z / math.sqrt(2)))
def sides(u, g, conv):
    """Two-piece normal. 'bfw': Britton, Fisher & Whitley 1998, Bank of England QB p. 37 (positive gamma narrows
    the upper side); 'fanplot': the package's reading (positive skew widens it); 'sym': skew ignored."""
    if conv == 'sym' or g == 0: return u, u
    a, b = u / math.sqrt(1 + g), u / math.sqrt(1 - g)
    return (b, a) if conv == 'bfw' else (a, b)
def cdf(x, m, u, g, conv):
    s1, s2 = sides(u, g, conv); w = s1 / (s1 + s2)
    return 2 * w * Phi((x - m) / s1) if x <= m else w + 2 * (1 - w) * (Phi((x - m) / s2) - .5)
CONV = ['bfw', 'fanplot', 'sym']
rep = {}
for r in B: rep.setdefault(r['t0'], []).append(r)
reports = sorted(rep)
assert len(reports) == 40
res = dict(n_reports=40, n_rows=512, conv={})
for c in CONV:
    byh = {}
    for r in B:
        h = round((r['t'] - r['t0']) * 4)
        if r['t'] in CPI:
            byh.setdefault(h, []).append(cdf(CPI[r['t']], r['m'], r['u'], r['g'], c))
    d = {h: dict(n=len(v), above95=sum(x > .95 for x in v), below5=sum(x < .05 for x in v)) for h, v in sorted(byh.items())}
    h8 = [r for r in B if round((r['t'] - r['t0']) * 4) == 8]
    p3 = [1 - cdf(3.0, r['m'], r['u'], r['g'], c) for r in h8]; y3 = [CPI[r['t']] > 3.0 for r in h8]
    p2 = [1 - cdf(2.0, r['m'], r['u'], r['g'], c) for r in h8]; y2 = [CPI[r['t']] > 2.0 for r in h8]
    res['conv'][c] = dict(by_horizon=d, h8_p_above3_sum=round(sum(p3), 2), h8_above3_count=sum(y3),
                          h8_brier_above3=round(sum((p - y) ** 2 for p, y in zip(p3, y3)) / 40, 4),
                          h8_p_above2_mean=round(sum(p2) / 40, 3), h8_above2_count=sum(y2))
sd = lambda v: math.sqrt(sum((x - sum(v) / len(v)) ** 2 for x in v) / len(v))
h8 = [r for r in B if round((r['t'] - r['t0']) * 4) == 8]; h0 = [r for r in B if r['t'] == r['t0']]
res['h8'] = dict(mode_sd=round(sd([r['m'] for r in h8]), 2), nowcast_mode_sd=round(sd([r['m'] for r in h0]), 2),
                 outturn_sd=round(sd([CPI[r['t']] for r in h8]), 2), mode_within_half_point=sum(abs(r['m'] - 2) <= .5 for r in h8),
                 outturn_within_half_point=sum(abs(CPI[r['t']] - 2) <= .5 for r in h8),
                 mode_range=[min(r['m'] for r in h8), max(r['m'] for r in h8)], outturn_range=[min(CPI[r['t']] for r in h8), max(CPI[r['t']] for r in h8)])
for k, v in res.items(): print(k, json.dumps(v)[:900])
json.dump(res, open(os.path.join(here, 'results.json'), 'w'), indent=1)
cpi = {f'{k:.2f}': v for k, v in sorted(CPI.items()) if 2001 <= k <= 2017}
data = dict(params={f'{t0:.2f}': [[r['t'], r['m'], r['u'], r['g']] for r in rep[t0]] for t0 in reports}, cpi=cpi, results=res)
open(os.path.join(here, 'data.js'), 'w').write('// generated by build.py; parameters: Bank of England, outturns: ONS D7G7 (OGL v3.0)\nconst DATA = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print('wrote data.js and results.json')
